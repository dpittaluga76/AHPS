"""Planner feature contracts and independently frozen default archive regression tests.

After baseline release, references were captured from exact git blobs at
1d436f3, including its checked-in DLL (not a rebuilt kernel), in an isolated
temporary directory. The capture child imported only the frozen compressor and
verified each archive with both frozen decoders before exiting and DLL cleanup.
See tests/fixtures/v5/default-features.json and its README for provenance.
The expected output must never be generated by the implementation under test,
by a test invocation, or by importing this module. Missing fixtures fail clearly.
"""

import contextlib
import ctypes
import dataclasses
import hashlib
import json
import lzma
from pathlib import Path
import struct
from types import SimpleNamespace
import unittest
from unittest import mock

import ahps


FEATURE_NAMES = ("exe32", "exe_split", "delta_split", "per_chunk")
REFERENCE_COMMIT = "1d436f33090276b64a841709393833f4e15bef27"
REFERENCE_CASES = {
    "whole": {},
    "chunked": {"EXTREME_LIMIT": 1024, "PLAN_CHUNK_LEN": 4096},
}
REFERENCE_PATH = Path(__file__).resolve().parent / "fixtures" / "v5" / "default-features.json"
REFERENCE_DOCUMENT = json.loads(REFERENCE_PATH.read_text(encoding="utf-8"))
FROZEN_ARCHIVE_RECORDS = {(record["engine"], record["case"]): record for record in REFERENCE_DOCUMENT["cases"]}
FROZEN_ARCHIVES_HEX = {key: record["archive_hex"] for key, record in FROZEN_ARCHIVE_RECORDS.items()}
FROZEN_REFERENCE_PROVENANCE = REFERENCE_DOCUMENT["reference"]


def make_x86_data(length=4096):
    """Deterministic CALL/RIP-relative regions; no filesystem or corpus input."""
    out = bytearray()
    record = 0
    while len(out) < length:
        out += b"\x55\x48\x89\xe5\x90"
        target = 0x4000 + (record % 7) * 0x80
        relative = (target - (len(out) + 5)) & 0xFFFFFFFF
        out += b"\xe8" + struct.pack("<I", relative)
        out += b"\x48\x8b\x05"
        relative = (0x18000 + (record % 11) * 16 - (len(out) + 4)) & 0xFFFFFFFF
        out += struct.pack("<I", relative)
        out += b"\x90\x5d\xc3"
        record += 1
    return bytes(out[:length])


def make_records(count=256):
    return b"".join(
        struct.pack("<QII", 1700000000000 + i * 1000 + i % 3, 50000 + i, i * 17 + 42)
        for i in range(count)
    )


def make_fixture_data():
    return make_x86_data() + make_records() + bytes((i * 73 + 19) & 0xFF for i in range(257))


def features_for_mask(mask):
    return ahps.PlanFeatures(exe32=bool(mask & 1), exe_split=bool(mask & 2))


def toggle_cases():
    cases = [("default", ahps.PlanFeatures())]
    cases += [("no_" + name, ahps.PlanFeatures(**{name: False})) for name in FEATURE_NAMES]
    cases += [
        ("no_x86", ahps.PlanFeatures(exe32=False, exe_split=False)),
        ("all_off", ahps.PlanFeatures(**dict.fromkeys(FEATURE_NAMES, False))),
    ]
    return cases


@contextlib.contextmanager
def thresholds(values):
    with contextlib.ExitStack() as stack:
        for name, value in values.items():
            stack.enter_context(mock.patch.object(ahps, name, value))
        yield


def archive_programs(archive):
    """Inspect emitted opcodes from the documented format, not report labels."""
    raw = lzma.decompress(archive)
    if raw[:5] != b"AHPS\x05":
        raise AssertionError("Feature settings must still write the v5 format")
    count, table_len, total_len, _ = struct.unpack_from("<IIQI", raw, 5)
    cursor, covered, programs = 25, 0, []
    for _ in range(count):
        length, steps = struct.unpack_from("<IB", raw, cursor)
        cursor += 5
        programs.append([raw[cursor + 5 * index] for index in range(steps)])
        cursor += 5 * steps
        covered += length
    if cursor != 25 + table_len or covered != total_len or cursor + total_len != len(raw):
        raise AssertionError("Encoded archive does not satisfy the documented segment layout")
    return programs


class FeatureAssertions(unittest.TestCase):
    def assert_programs_respect(self, programs, features):
        operations = {opcode for program in programs for opcode in program}
        if not features.exe32:
            self.assertNotIn(ahps.OP_EXE32, operations)
        if not features.exe_split:
            self.assertNotIn(ahps.OP_EXE_SPLIT, operations)
        if not features.delta_split:
            self.assertNotIn(ahps.OP_SPLIT, operations)


class PlanFeatureConfigTests(FeatureAssertions):
    def test_default_features_are_enabled_and_frozen(self):
        features = ahps.PlanFeatures()
        self.assertEqual(dataclasses.asdict(features), dict.fromkeys(FEATURE_NAMES, True))
        with self.assertRaises(dataclasses.FrozenInstanceError):
            features.exe32 = False

    def test_each_field_requires_a_real_bool(self):
        for name in FEATURE_NAMES:
            for invalid in (0, 1, -1, None, "false", 1.0, [], {}):
                with self.subTest(field=name, value=invalid):
                    with self.assertRaises((TypeError, ValueError)):
                        ahps.PlanFeatures(**{name: invalid})

    def test_compressor_requires_a_feature_configuration(self):
        for invalid in (None, True, {}, "default"):
            with self.subTest(features=invalid):
                with self.assertRaises((TypeError, ValueError)):
                    ahps.ahps_compress_bytes(b"small input", features=invalid)


class MaskedScoringTests(FeatureAssertions):
    def test_python_scorer_never_runs_a_disabled_x86_lift(self):
        data = make_x86_data(1025)
        for mask in range(4):
            features = features_for_mask(mask)
            enabled = ({ahps.OP_EXE32} if mask & 1 else set()) | (
                {ahps.OP_EXE_SPLIT} if mask & 2 else set()
            )
            with self.subTest(mask=mask):
                with mock.patch.object(ahps, "py_forward_lift", wraps=ahps.py_forward_lift) as forward:
                    costs, _, _ = ahps.py_score_block(data, 0xFFFFFFF0, features=features)
                seen = {call.args[0] for call in forward.call_args_list}
                self.assertEqual(seen & {ahps.OP_EXE32, ahps.OP_EXE_SPLIT}, enabled)
                if not enabled:
                    self.assertEqual(costs[ahps.SLOT_EXE], ahps.COST_NONE)
                else:
                    self.assertLess(costs[ahps.SLOT_EXE], ahps.COST_NONE)

    @unittest.skipIf(ahps.SIMD_BRIDGE.lib is None, "requires the native kernel")
    def test_native_masks_match_python_x86_costs_and_preserve_other_slots(self):
        self.assertTrue(hasattr(ahps.SIMD_BRIDGE.lib, "ahps_score_buffer_ex"), "rebuild the feature-aware kernel")
        data, block_size = make_x86_data(1025), 256
        full_costs, full_local = ahps.SIMD_BRIDGE.score_all(data, block_size)
        for mask in range(4):
            with self.subTest(mask=mask):
                native_costs, local = ahps.SIMD_BRIDGE.score_all(data, block_size, exe_flags=mask)
                self.assertEqual(local, full_local)
                self.assertEqual(len(native_costs), len(full_costs))
                for block, offset in enumerate(range(0, len(data), block_size)):
                    python_costs, _, _ = ahps.py_score_block(
                        data[offset:offset + block_size], offset, features=features_for_mask(mask)
                    )
                    row = block * ahps.NUM_SLOTS
                    if mask == 0:
                        self.assertEqual(native_costs[row + ahps.SLOT_EXE], ahps.COST_NONE)
                    else:
                        self.assertAlmostEqual(
                            native_costs[row + ahps.SLOT_EXE], python_costs[ahps.SLOT_EXE], places=6
                        )
                    for slot in range(ahps.NUM_SLOTS):
                        if slot != ahps.SLOT_EXE:
                            self.assertEqual(native_costs[row + slot], full_costs[row + slot])

    @unittest.skipIf(ahps.SIMD_BRIDGE.lib is None, "requires the native kernel")
    def test_legacy_native_entrypoint_matches_extended_flags_three(self):
        lib = ahps.SIMD_BRIDGE.lib
        self.assertTrue(hasattr(lib, "ahps_score_buffer_ex"), "rebuild the feature-aware kernel")
        self.assertEqual(lib.ahps_abi_version(), 206)
        data, block_size = make_x86_data(1025), 256
        blocks = (len(data) + block_size - 1) // block_size
        old_costs = (ctypes.c_double * (blocks * ahps.NUM_SLOTS))()
        new_costs = (ctypes.c_double * (blocks * ahps.NUM_SLOTS))()
        old_local = (ctypes.c_uint8 * (blocks * 5))()
        new_local = (ctypes.c_uint8 * (blocks * 5))()
        self.assertEqual(lib.ahps_score_buffer(data, len(data), block_size, old_costs, old_local), 1)
        self.assertEqual(lib.ahps_score_buffer_ex(data, len(data), block_size, 3, new_costs, new_local), 1)
        self.assertEqual(list(old_costs), list(new_costs))
        self.assertEqual(bytes(old_local), bytes(new_local))

    def test_missing_native_extension_rejects_masks_without_silent_fallback(self):
        legacy = mock.Mock(return_value=1)
        bridge = object.__new__(ahps.NativeSIMDBridge)
        bridge.lib = SimpleNamespace(ahps_score_buffer=legacy)
        for mask in (0, 1, 2):
            with self.subTest(mask=mask):
                with self.assertRaises(RuntimeError):
                    bridge.score_all(b"synthetic", 4, exe_flags=mask)
        legacy.assert_not_called()
        bridge.score_all(b"synthetic", 4)
        legacy.assert_called_once()


class FeaturePlannerTests(FeatureAssertions):
    def test_rivals_include_only_enabled_x86_programs(self):
        data = make_x86_data()
        self.assertTrue(ahps.looks_like_x86(data))
        for mask in range(4):
            with self.subTest(mask=mask):
                features = features_for_mask(mask)
                rivals = ahps.rival_plans(data, [ahps.Segment(0, len(data), [])], features=features)
                operations = {op for plan in rivals for seg in plan for op, _ in seg.program}
                expected = ({ahps.OP_EXE32} if mask & 1 else set()) | (
                    {ahps.OP_EXE_SPLIT} if mask & 2 else set()
                )
                self.assertEqual(operations, expected)

    def test_delta_refinement_does_not_trial_a_disabled_split(self):
        data = make_records()
        features = ahps.PlanFeatures(delta_split=False)
        for use_c in ([False, True] if ahps.SIMD_BRIDGE.lib is not None else [False]):
            with self.subTest(use_c=use_c):
                segment = ahps.Segment(0, len(data), [(ahps.OP_DELTA1_LANE, bytes([16, 0, 0, 0]))])
                with thresholds({"CHAIN_MIN_LEN": 256}), \
                        mock.patch.object(ahps, "apply_program", wraps=ahps.apply_program) as apply:
                    ahps.refine_chain(segment, data, use_c, features=features)
                self.assertTrue(apply.called, "fixture did not reach chain refinement")
                for trial in apply.call_args_list:
                    self.assert_programs_respect([[op for op, _ in trial.args[0]]], features)
                self.assert_programs_respect([[op for op, _ in segment.program]], features)

    def test_x86_refinement_does_not_trial_a_disabled_x86_program(self):
        data = make_x86_data(1024)
        for mask in (1, 2):
            features = features_for_mask(mask)
            allowed = ahps.OP_EXE32 if mask == 1 else ahps.OP_EXE_SPLIT
            for use_c in ([False, True] if ahps.SIMD_BRIDGE.lib is not None else [False]):
                with self.subTest(mask=mask, use_c=use_c):
                    segment = ahps.Segment(0, len(data), [(allowed, bytes(4))])
                    with thresholds({"CHAIN_MIN_LEN": 256}), \
                            mock.patch.object(ahps, "apply_program", wraps=ahps.apply_program) as apply:
                        ahps.refine_chain(segment, data, use_c, features=features)
                    self.assertTrue(apply.called, "fixture did not reach x86 refinement")
                    for trial in apply.call_args_list:
                        self.assert_programs_respect([[op for op, _ in trial.args[0]]], features)
                    self.assertEqual([op for op, _ in segment.program], [allowed])

    def test_planned_segments_exclude_disabled_opcodes(self):
        data = make_fixture_data()
        for name, features in toggle_cases():
            for use_c in ([False, True] if ahps.SIMD_BRIDGE.lib is not None else [False]):
                with self.subTest(toggle=name, use_c=use_c):
                    plan = ahps.plan_segments(data, 512, use_c, features=features)
                    self.assertEqual(sum(seg.length for seg in plan), len(data))
                    self.assert_programs_respect([[op for op, _ in seg.program] for seg in plan], features)

    def test_per_chunk_false_uses_whole_file_search_above_threshold(self):
        data = make_fixture_data()
        features = ahps.PlanFeatures(per_chunk=False)
        with thresholds(REFERENCE_CASES["chunked"]):
            with mock.patch.object(ahps, "chunked_plan", side_effect=AssertionError("disabled chunk planner ran")):
                archive, report = ahps.ahps_compress_bytes(
                    data, 512, True, 0, features=features
                )
        self.assertEqual(report.features, features)
        self.assertEqual(ahps.ahps_decompress_bytes(archive, True), data)

    def test_enabled_chunk_path_visits_multiple_small_chunks(self):
        data = make_fixture_data()
        features = ahps.PlanFeatures()
        with thresholds(REFERENCE_CASES["chunked"]):
            with mock.patch.object(ahps, "plan_segments", wraps=ahps.plan_segments) as planner:
                archive, report = ahps.ahps_compress_bytes(data, 512, True, 0, features=features)
        self.assertGreaterEqual(len(planner.call_args_list), 2)
        self.assertTrue(all(len(call.args[0]) <= 4096 for call in planner.call_args_list))
        self.assertEqual(report.features, features)
        self.assertEqual(ahps.ahps_decompress_bytes(archive, True), data)


class FeatureArchiveTests(FeatureAssertions):
    def test_python_toggles_report_configuration_and_emit_only_enabled_programs(self):
        data = make_fixture_data()
        with thresholds(REFERENCE_CASES["chunked"]):
            for name, features in toggle_cases():
                with self.subTest(toggle=name):
                    archive, report = ahps.ahps_compress_bytes(data, 512, True, 0, features=features)
                    self.assertEqual(report.features, features)
                    self.assert_programs_respect(archive_programs(archive), features)
                    self.assertEqual(ahps.ahps_decompress_bytes(archive, True), data)

    @unittest.skipIf(ahps.SIMD_BRIDGE.lib is None, "requires native/Python interoperability")
    def test_each_toggle_keeps_every_encoder_decoder_pair_interoperable(self):
        data = make_fixture_data()
        with thresholds(REFERENCE_CASES["chunked"]):
            for name, features in toggle_cases():
                for encode_python in (False, True):
                    with self.subTest(toggle=name, encode_python=encode_python):
                        archive, report = ahps.ahps_compress_bytes(
                            data, 512, encode_python, 0, features=features
                        )
                        self.assertEqual(report.features, features)
                        self.assert_programs_respect(archive_programs(archive), features)
                        for decode_python in (False, True):
                            self.assertEqual(ahps.ahps_decompress_bytes(archive, decode_python), data)


class FrozenDefaultOutputTests(FeatureAssertions):
    def assert_frozen_output(self, engine, force_python):
        self.assertEqual(FROZEN_REFERENCE_PROVENANCE["commit"], REFERENCE_COMMIT)
        data = make_fixture_data()
        self.assertEqual(len(data), REFERENCE_DOCUMENT["fixture"]["bytes"])
        self.assertEqual(hashlib.sha256(data).hexdigest(), REFERENCE_DOCUMENT["fixture"]["sha256"])
        for case, settings in REFERENCE_CASES.items():
            key = (engine, case)
            with self.subTest(engine=engine, case=case):
                self.assertIn(
                    key, FROZEN_ARCHIVES_HEX,
                    "Independent 1d436f3 reference is missing; never regenerate from candidate",
                )
                record = FROZEN_ARCHIVE_RECORDS[key]
                self.assertEqual(record["planner_overrides"], settings)
                self.assertEqual(
                    record["arguments"], {"block_size": 512, "force_python": force_python, "lzma_preset": 0}
                )
                expected = bytes.fromhex(FROZEN_ARCHIVES_HEX[key])
                self.assertTrue(expected)
                self.assertEqual(len(expected), record["archive_bytes"])
                self.assertEqual(hashlib.sha256(expected).hexdigest(), record["archive_sha256"])
                with thresholds(settings):
                    implicit, implicit_report = ahps.ahps_compress_bytes(data, 512, force_python, 0)
                    explicit, explicit_report = ahps.ahps_compress_bytes(
                        data, 512, force_python, 0, features=ahps.PlanFeatures()
                    )
                self.assertEqual(implicit, expected)
                self.assertEqual(explicit, expected)
                self.assertEqual(implicit_report.features, ahps.PlanFeatures())
                self.assertEqual(explicit_report.features, ahps.PlanFeatures())
                self.assertEqual(ahps.ahps_decompress_bytes(expected, True), data)

    def test_default_python_output_matches_frozen_reference(self):
        self.assert_frozen_output("python", True)

    @unittest.skipIf(ahps.SIMD_BRIDGE.lib is None, "requires the native kernel")
    def test_default_native_output_matches_frozen_reference(self):
        self.assert_frozen_output("native", False)


